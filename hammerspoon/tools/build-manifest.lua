#!/usr/bin/env lua
-- =====================================================================
-- BUILD-MANIFEST — what this release carries, so a half-install can be
-- told from a finished one in five seconds
-- =====================================================================
--     lua tools/build-manifest.lua .          ← writes MANIFEST.txt
--     lua tools/build-manifest.lua . --check  ← verifies it is current
--
-- 6.399.0 — the file modules/install_check.lua reads. One row per
-- RUNTIME file: the path relative to ~/.hammerspoon, a TAB, and the byte
-- count. Comments start with #; the version is a comment the reader
-- parses, so a manifest can say which release it belongs to.
--
-- 🚨 GENERATED, NEVER HAND-WRITTEN, for the reason RESOLVED-FEATURE-
-- REQUESTS.txt and TESTING.md are: a list kept in step by hand is stale
-- the first time a file changes, and a stale manifest is worse than
-- none — every row would disagree and he would learn to ignore the one
-- instrument built to catch a real half-install (6.269.0).
--
-- ---- 📏 WHAT COUNTS AS RUNTIME, AND WHY THE LINE IS THERE ------------
-- What his Mac LOADS or STARTS by itself:
--     init.lua · core/*.lua · modules/*.lua · tools/hs-stall-guard.sh
-- Everything else is deliberately out, and install_check's report NAMES
-- each omission rather than leaving it to be discovered:
--   · CHANGELOG.md — read at runtime by core/changelog_csv.lua, which
--     already checks its ENTRY for this version. A better question than
--     its length, and two answers to one question is 6.317.0's warning.
--   · snippets/bundled.lua — GENERATED, and he can legitimately rebuild
--     it on his own Mac from packs this archive never saw, so a size row
--     would disagree for a reason that is not a half-install. Its own
--     instrument exists: _G.snippetsReport() counts what loaded.
--   · the docs, tests/ and the other tools — not run by his Mac, and
--     tools/hs-install.sh has never copied a .md.
--
-- 🔒 A PATH WITH A TAB IN IT WOULD WRITE AN UNPARSEABLE ROW, so this
-- REFUSES rather than writing one: the reader splits on a tab, and a row
-- it cannot parse is a file that silently stops being checked. Nothing
-- in this tree has one; the guard is for the day something does.
-- =====================================================================

local HS    = arg[1] or "."
local CHECK = false
for i = 2, #arg do if arg[i] == "--check" then CHECK = true end end

local OUT = HS .. "/MANIFEST.txt"

local function readAll(p)
    local f = io.open(p, "r"); if not f then return nil end
    local s = f:read("*a"); f:close(); return s
end

local function sizeOf(p)
    local f = io.open(p, "rb"); if not f then return nil end
    local n = f:seek("end"); f:close(); return n
end

-- `ls` rather than lfs: this runs on the gate's Linux and on a Mac, and
-- neither is guaranteed to have LuaFileSystem.
local function luaFilesIn(dir)
    local out = {}
    local p = io.popen("ls -1 '" .. HS .. "/" .. dir .. "' 2>/dev/null")
    if not p then return out end
    for line in p:lines() do
        if line:sub(-4) == ".lua" then out[#out + 1] = dir .. "/" .. line end
    end
    p:close()
    table.sort(out)
    return out
end

local init = readAll(HS .. "/init.lua")
if not init then io.stderr:write("❌ no init.lua in " .. HS .. "\n"); os.exit(1) end
local version = init:match('_G%.configVersion%s*=%s*"([^"]+)"')
if not version then
    io.stderr:write("❌ init.lua has no _G.configVersion — refusing to stamp a manifest\n")
    os.exit(1)
end

local files = { "init.lua" }
for _, f in ipairs(luaFilesIn("core"))    do files[#files + 1] = f end
for _, f in ipairs(luaFilesIn("modules")) do files[#files + 1] = f end
files[#files + 1] = "tools/hs-stall-guard.sh"

local rows, total, missing = {}, 0, {}
for _, rel in ipairs(files) do
    if rel:find("\t", 1, true) then
        io.stderr:write("❌ a path holds a TAB and would write an unparseable row: "
                        .. rel .. "\n")
        os.exit(1)
    end
    local n = sizeOf(HS .. "/" .. rel)
    if n == nil then
        missing[#missing + 1] = rel
    else
        rows[#rows + 1] = rel .. "\t" .. tostring(n)
        total = total + n
    end
end

if #missing > 0 then
    io.stderr:write("❌ these runtime files are not in the tree: "
                    .. table.concat(missing, ", ") .. "\n")
    os.exit(1)
end

local L = {}
L[#L + 1] = "# MANIFEST — what this release carries, one row per runtime file"
L[#L + 1] = "# version: " .. version
L[#L + 1] = "# " .. tostring(#rows) .. " file(s), " .. tostring(total) .. " bytes"
L[#L + 1] = "#"
L[#L + 1] = "# Read by modules/install_check.lua: _G.installCheck() stats each path"
L[#L + 1] = "# below, relative to ~/.hammerspoon, and names every file that disagrees."
L[#L + 1] = "# <path><TAB><bytes>.  Generated by tools/build-manifest.lua — never"
L[#L + 1] = "# hand-edited: a stale manifest would make every row disagree."
L[#L + 1] = "#"
L[#L + 1] = "# NOT HERE, on purpose: CHANGELOG.md (core/changelog_csv.lua checks its"
L[#L + 1] = "# ENTRY for this version, which is a better question than its length) ·"
L[#L + 1] = "# snippets/bundled.lua (generated, and rebuildable on his own Mac) · the"
L[#L + 1] = "# docs, tests/ and the other tools (not loaded or started by the config)."
for _, r in ipairs(rows) do L[#L + 1] = r end

local text = table.concat(L, "\n") .. "\n"

if CHECK then
    local have = readAll(OUT)
    if have ~= text then
        io.stderr:write("❌ MANIFEST.txt is out of date — run tools/build-manifest.lua\n")
        os.exit(1)
    end
    print("✅ MANIFEST.txt is current — " .. #rows .. " file(s), version " .. version)
    os.exit(0)
end

local f = assert(io.open(OUT, "w")); f:write(text); f:close()
print("✍️  wrote " .. OUT .. " — " .. #rows .. " runtime file(s), "
      .. total .. " bytes, version " .. version)
